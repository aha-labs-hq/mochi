#!/bin/zsh -l
# Derives everything the film reads from public/ out of its sources, so
# public/ holds nothing that is not rebuilt here or by score.ts and foley.ts:
#   frames/*.png (the stills the cuts show)  → public/stills/*.jpg
#   clips.json's chosen Seedance takes       → public/clips/<name>/NNN.jpg, src/clips.gen.ts
#   the app's introduction avatars           → public/people/*.png
#   the app's icon                          → public/mochi/MochiAppIcon.png
#   brand/ (the Aha Labs lockup, by tools/brand.py) → public/brand/
set -euo pipefail
cd "${0:A:h}/.."
app=../controlApp
rm -rf public/stills public/people public/mochi public/clips public/brand
mkdir -p clips public/stills public/people public/mochi public/clips public/brand

for f in frames/*.png; do magick $f -quality 92 public/stills/${f:t:r}.jpg; done

# A take is fetched by its provider task when absent, and must match its
# recorded hash. Only every other frame is kept: the film shows its motion at
# twelve exposures a second, so file k is source frame 2k.
counts=()
for name in $(jq -r 'del(.rejected) | keys[]' clips.json); do
  take=$(jq -r --arg n $name '.[$n].take' clips.json)
  file=clips/$take.mp4
  [[ -f $file ]] || curl -fsSL --max-time 300 "${MOCHI_MOTION_OUTPUT_BASE:?set MOCHI_MOTION_OUTPUT_BASE to the provider-output base URL}/$(jq -r --arg n $name '.[$n].task' clips.json).mp4" -o $file
  [[ $(shasum -a 256 $file | awk '{print $1}') == $(jq -r --arg n $name '.[$n].sha256' clips.json) ]] || { echo "$file does not match clips.json" >&2; exit 1; }
  mkdir -p public/clips/$name
  ffmpeg -nostdin -hide_banner -loglevel error -i $file -vf "select='not(mod(n\,2))'" -fps_mode vfr -q:v 2 -start_number 0 public/clips/$name/%03d.jpg
  size=$(ffprobe -v error -select_streams v -show_entries stream=width,height -of csv=p=0:s=, $file)
  counts+=("  \"$name\": { exposures: $(ls public/clips/$name | wc -l | tr -d ' '), width: ${size%,*}, height: ${size#*,} },")
done
print -l "// Generated by tools/assets.sh from clips.json. Do not edit." \
  "/** Each chosen take: its exposures at twelve a second, and its size. */" \
  "export const clips = {" $counts "} as const;" > src/clips.gen.ts

for p in nora jules evan riley mochi; do cp $app/src/ui/assets/introduction/$p.png public/people/; done
cp $app/Resources/MochiAppIcon.png public/mochi/
cp brand/*.svg public/brand/
echo "stills $(ls public/stills | wc -l | tr -d ' '); clips: ${counts[*]}"
