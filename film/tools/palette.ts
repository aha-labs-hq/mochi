/**
 * Writes src/palette.gen.ts from Mochi's palette, the one owner of its
 * colours for the companion and the website (controlApp/src/ui/palette.css).
 */
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const css = await readFile(join(root, "../controlApp/src/ui/palette.css"), "utf8");
const colours = Object.fromEntries(
  [...css.matchAll(/--color-([a-z-]+):\s*(#[0-9a-f]{6,8});/g)].map(([, name, value]) => [
    name!.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase()),
    value!,
  ]),
);
for (const name of ["ink", "muted", "hairline", "surface", "card", "note", "primary", "actionSoft"])
  if (!colours[name]) throw new Error(`palette.css lacks --color-${name}`);
await writeFile(
  join(root, "src/palette.gen.ts"),
  `// Generated by tools/palette.ts from controlApp/src/ui/palette.css. Do not edit.\nexport const palette = ${JSON.stringify(colours, null, 2)} as const;\n`,
);
console.log(`palette: ${Object.keys(colours).length} colours`);
